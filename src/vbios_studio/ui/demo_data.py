from vbios_studio.domain.models import DocumentSnapshot, FieldSnapshot, ImageSnapshot


def _field(
    key: str,
    label: str,
    section: str,
    unit: str,
    current: str,
    minimum: str | None,
    maximum: str | None,
    risk: str,
    offset: int,
    *,
    default: str | None = None,
    editable: bool = True,
    opt_in: bool = False,
    experimental: bool = False,
    description: str = "",
) -> FieldSnapshot:
    return FieldSnapshot(
        key=key,
        label=label,
        section=section,
        unit=unit,
        current=current,
        default=default if default is not None else current,
        minimum=minimum,
        maximum=maximum,
        risk=risk,  # type: ignore[arg-type]
        offset=offset,
        editable=editable,
        opt_in=opt_in,
        experimental=experimental,
        description=description,
    )


